export type AssistantLanguage = 'zh' | 'ja';

/** The app sends one interface language. Only the supported languages can affect the prompt. */
export function assistantLanguage(header: string | undefined): AssistantLanguage {
  return /^ja(?:-[a-z0-9]{1,8})*$/i.test(header?.trim() ?? '') ? 'ja' : 'zh';
}

